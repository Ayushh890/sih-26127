function renderAt(path: string, routeEl: { path: string; el: ReactNode }) {
  const qc = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  return render(
    <QueryClientProvider client={qc}>
      <AuthProvider>
        <ScopeProvider>
          <MemoryRouter initialEntries={[path]}>
            <Routes>
              <Route path={routeEl.path} element={routeEl.el} />
            </Routes>
          </MemoryRouter>
        </ScopeProvider>
      </AuthProvider>
    </QueryClientProvider>,
  );
}

describe("Alerts page", () => {
  it("lists alerts with filters from the URL and acknowledges via POST /api/alerts/{code}/acknowledge", async () => {
    let current = alert();
    routes["GET /api/alerts"] = () => ({ ...scopeInfo, total: 1, counts_7d: { NEW: 1 }, results: [current] });
    routes["POST /api/alerts/ALR-20260930-000001/acknowledge"] = () => {
      current = alert({ status: "ACKNOWLEDGED", acknowledged_by: "admin", acknowledged_at: "2026-09-30T12:40:00+00:00" });
      return current;
    };
    renderAt("/alerts?status=OPEN&severity=HIGH", { path: "/alerts", el: <Alerts /> });

    const row = await screen.findByTestId("alert-row-ALR-20260930-000001");
    expect(within(row).getByText("IMPOSSIBLE_TRAVEL")).toBeInTheDocument();
    expect(screen.getByText("Synthetic demo data generated by the demo traffic scenario.")).toBeInTheDocument();
    const list = calls.find((c) => c.path === "/api/alerts");
    expect(list?.search).toContain("status=OPEN");
    expect(list?.search).toContain("severity=HIGH");

    await userEvent.click(within(row).getByRole("button", { name: "Ack" }));
    await waitFor(() => expect(calls.some((c) => c.method === "POST" && c.path === "/api/alerts/ALR-20260930-000001/acknowledge")).toBe(true));
    await waitFor(() => expect(within(screen.getByTestId("alert-row-ALR-20260930-000001")).getByText("ACKNOWLEDGED")).toBeInTheDocument());
  });

  it("resolves with a note and prepends live alert_created events", async () => {
    let server = [alert()];
    routes["GET /api/alerts"] = () => ({ ...scopeInfo, total: server.length, counts_7d: { NEW: server.length }, results: server });
    routes["POST /api/alerts/ALR-20260930-000001/resolve"] = () => alert({ status: "RESOLVED", resolved_by: "admin", resolution_note: "misread plate" });
    renderAt("/alerts", { path: "/alerts", el: <Alerts /> });
    const first = await screen.findByTestId("alert-row-ALR-20260930-000001");

    await userEvent.click(within(first).getByRole("button", { name: "Resolve…" }));
    const dialog = await screen.findByRole("dialog");
    await userEvent.type(within(dialog).getByRole("textbox"), "misread plate");
    await userEvent.click(within(dialog).getByRole("button", { name: "Resolve" }));
    await waitFor(() => {
      const c = calls.find((x) => x.method === "POST" && x.path.endsWith("/resolve"));
      expect(c?.body).toEqual({ note: "misread plate" });
    });

    const fresh = alert({ id: 7, code: "ALR-20260930-000007", type: "WRONG_WAY", title: "Wrong-way vehicle at CAM-06" });
    server = [fresh, ...server];
    act(() => live.handlers.get("alert_created")?.forEach((h) => h({ type: "alert_created", data: fresh })));
    const row = await screen.findByTestId("alert-row-ALR-20260930-000007");
    expect(row.className).toContain("bg-cyan-500/15"); // brief live highlight
    await waitFor(() => expect(calls.filter((c) => c.path === "/api/alerts").length).toBeGreaterThanOrEqual(2)); // re-synced from server
  });
});

