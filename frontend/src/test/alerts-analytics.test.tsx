// Capture live-event subscriptions so tests can push WebSocket events.
const live = vi.hoisted(() => ({ handlers: new Map<string, Set<(ev: { type: string; data: unknown }) => void>>() }));
vi.mock("../lib/ws", async () => {
  const { useEffect, useRef } = await import("react");
  return {
    useConnState: () => "open",
    useLiveEvent: (types: string | string[], handler: (ev: { type: string; data: unknown }) => void) => {
      const ref = useRef(handler);
      ref.current = handler;
      const key = Array.isArray(types) ? types.join(",") : types;
      useEffect(() => {
        const fns = key.split(",").map((t) => {
          const fn = (ev: { type: string; data: unknown }) => ref.current(ev);
          if (!live.handlers.has(t)) live.handlers.set(t, new Set());
          live.handlers.get(t)!.add(fn);
          return [t, fn] as const;
        });
        return () => fns.forEach(([t, fn]) => live.handlers.get(t)?.delete(fn));
      }, [key]);
    },
  };
});

