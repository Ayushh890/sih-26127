describe("Watchlist page", () => {
  it("explains rule-only alerting and creates an entry with the backend fields", async () => {
    let entries: unknown[] = [];
    routes["GET /api/watchlist"] = () => ({ results: entries });
    routes["POST /api/watchlist"] = (_u, init) => {
      const b = JSON.parse(String(init?.body));
      const e = { id: 1, ...b, active: true, created_by: "admin", created_at: "2026-09-30T12:40:00+00:00", last_match_at: null, match_count: 0 };
      entries = [e];
      return json(e, 201);
    };
    renderAt("/watchlist", { path: "/watchlist", el: <Watchlist /> });
    expect(await screen.findByText(/No plate is ever flagged by default/)).toBeInTheDocument();
    expect(await screen.findByText(/The watchlist is empty/)).toBeInTheDocument();

    await userEvent.click(screen.getByRole("button", { name: "+ Add plate" }));
    const dialog = await screen.findByRole("dialog");
    const [plate, reason] = within(dialog).getAllByRole("textbox");
    await userEvent.type(plate, "UP32HN4412");
    await userEvent.type(reason, "stolen vehicle report");
    await userEvent.click(within(dialog).getByRole("button", { name: "Add to watchlist" }));
    await waitFor(() => {
      const c = calls.find((x) => x.method === "POST" && x.path === "/api/watchlist");
      expect(c?.body).toMatchObject({ plate: "UP32HN4412", reason: "stolen vehicle report", priority: "MEDIUM", match_mode: "exact", expires_at: null });
    });
    expect(await screen.findByText("UP32HN4412")).toBeInTheDocument();
  });
});
